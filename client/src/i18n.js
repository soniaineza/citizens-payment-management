const STORAGE_KEY = 'lang';
const DEFAULT_LANG = 'fr';
let current = 'fr';
try {
  current = localStorage.getItem(STORAGE_KEY) || DEFAULT_LANG;
} catch {
  current = DEFAULT_LANG;
}
const listeners = new Set();

export function getLang() {
  return current;
}

export function setLang(lang) {
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {}
  listeners.forEach((l) => l());
}

export function t(key) {
  const dict = translations[current] || translations.en;
  return dict[key] ?? translations.en[key] ?? key;
}

export function apiError(err) {
  const raw = err?.response?.data?.error;
  if (!raw) return t('common.oops');
  const dict = serverMessages[current] || serverMessages.en;
  return dict[raw] || translations[current][raw] || raw;
}

export function useI18n() {
  const [, force] = useState(0);
  useEffect(() => {
    const listener = () => force((x) => x + 1);
    listeners.add(listener);
    return () => listeners.delete(listener);
  }, []);
  return { t, lang: current, setLang };
}

export function formatMoney(n) {
  return Number(n || 0).toLocaleString(current === 'fr' ? 'fr-FR' : undefined, {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
}

export function formatDate(d) {
  if (!d) return '—';
  const date = new Date(d);
  if (isNaN(date)) return d;
  return date.toLocaleDateString(current === 'fr' ? 'fr-FR' : undefined);
}